"""Build web_page.h from web_page.html: run after editing the page, then compile.

    py -3 make_web_page.py

The header holds the page twice: as text (WEB_PAGE, for a client that doesn't
accept gzip) and gzipped (WEB_PAGE_GZ, what browsers get). Gzip matters on this
board: its lwIP has ~1 KB in flight per round trip, so the 14 KB page took
0.5-2.3 s to load and the gzipped copy is about a third of that.
"""
import gzip
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "web_page.html")
DST = os.path.join(HERE, "web_page.h")


def main():
    html = open(SRC, encoding="utf-8").read()
    if ')GACP"' in html:
        raise SystemExit('web_page.html must not contain )GACP" (the raw-string delimiter)')
    raw = html.encode("utf-8")
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    rows = []
    for k in range(0, len(gz), 20):
        rows.append("  " + ",".join(f"0x{b:02x}" for b in gz[k:k + 20]) + ",")
    out = f"""#pragma once
// GENERATED by make_web_page.py from web_page.html. Edit the .html, then run
// `py -3 make_web_page.py`; changes made here are overwritten.
//
// The page the board serves on port 8080, beside the GUI protocol (the "web
// page" section of the .ino).
// One file, no external resources, so it works on a network with no internet.
// It polls GET /api/live once a second and draws the persistence map from the
// frames in it; the only thing it can change is the load relay
// (POST /api/relay?on=0|1 with the X-GACP header).
static const char WEB_PAGE[] = R"GACP({html})GACP";

// the same, gzip -9: {len(raw)} -> {len(gz)} bytes
static const uint8_t WEB_PAGE_GZ[] = {{
{chr(10).join(rows)}
}};
"""
    open(DST, "w", encoding="utf-8", newline="\n").write(out)
    print(f"web_page.h: {len(raw)} bytes, gzipped {len(gz)}")


if __name__ == "__main__":
    main()
